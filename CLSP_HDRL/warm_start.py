"""AMBS-based warm start of the HIGH actor-critic network.

HIGH is pretrained by behavior cloning on (state, action) pairs generated by the AMBS heuristic before
PPO starts; LOW starts from its random initialization.

- AMBS only decides what/how much to produce; transitions, demand and costs come from the real
  CLSPHierEnv / CLSPHierEnv2 step(), run on an isolated clone of the training environment.
- Decisions are ports of AMBS_Heuristic_SCLSP.ipynb (S-CLSP) and AMBS_Heuristic_SCLSP_SD.ipynb (SD).
- Thresholds (Bmin, Hmax, Zmax[, lam]) are not calibrated here: they come from AMBS_PARAMS_REGISTRY
  (grid search done offline in those notebooks) or from the `ambs_params` argument.
- HIGH labels are 1{q_i > 0}. Each AMBS quantity is passed to env.step() as a LOW action (fraction of
q_cap).
- S-CLSP-SD: the AMBS-SD sequence is passed as pseudo scores, and the pretraining adds a Plackett-Luce
  order term (`rank_coef`) so the HIGH logits follow it.
- The actor uses the same MaskedBernoulli as PPO; the critic regresses discounted Monte-Carlo returns.
"""

