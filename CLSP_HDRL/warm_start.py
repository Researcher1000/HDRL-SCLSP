def get_ambs_params(instance_id, is_sd):
    """Look up calibrated AMBS thresholds for `instance_id` in `AMBS_PARAMS_REGISTRY` and build the matching
    `AMBSParams`/`AMBSParamsSD`.
    """
    if instance_id not in AMBS_PARAMS_REGISTRY:
        raise KeyError(
            f"No AMBS hyperparameters found for instance_id={instance_id!r} in "
            f"AMBS_PARAMS_REGISTRY (CLSP_HDRL/warm_start.py). Add an entry there "
            f"(Bmin, Hmax, Zmax[, lam] for S-CLSP-SD) with "
            f"your own calibrated values, or pass `ambs_params=` directly to "
            f"`warm_start_policies`."
        )
    p = dict(AMBS_PARAMS_REGISTRY[instance_id])
    if is_sd:
        return AMBSParamsSD(Bmin=p["Bmin"], Hmax=p["Hmax"], Zmax=p["Zmax"], lam=p.get("lam", 0.0))
    return AMBSParams(Bmin=p["Bmin"], Hmax=p["Hmax"], Zmax=p["Zmax"])


# EOQ helpers
def _eoq_ceil(mu, k, h):
    """Q_i = ceil(sqrt(2 * mu_i * k_i / h_i)), as in AMBS_Heuristic_SCLSP.ipynb."""
    mu = np.asarray(mu, dtype=np.float64)
    k = np.asarray(k, dtype=np.float64)
    h = np.asarray(h, dtype=np.float64)
    return np.ceil(np.sqrt(2.0 * mu * k / h)).astype(np.int64)


def _eoq_cost(mu, k, h, Q):
    """EOQCost_i = k_i*mu_i/Q_i + h_i*Q_i/2 -- matches AMBS_Heuristic_SCLSP.ipynb."""
    mu = np.asarray(mu, dtype=np.float64)
    k = np.asarray(k, dtype=np.float64)
    h = np.asarray(h, dtype=np.float64)
    return k * mu / Q + h * Q / 2.0


# Expected backlog (matches AMBS_Heuristic_SCLSP*.ipynb's DemandGenerator.expected_backlog).
def _expected_backlog_units(a_unif, b_unif, i, s):
    """Raw expected UNITS of backlog for product i given inventory+planned position `s` (NOT multiplied by
    b_i).
    """
    lo, hi = int(a_unif[i]), int(b_unif[i])
    n = hi - lo + 1
    total = 0.0
    p = 1.0 / n
    for d in range(lo, hi + 1):
        total += p * max(d - s, 0.0)
    return total


# Per-period AMBS decision
def _ambs_decide_period_nonsd(env, I, iSU, params, Q, C):
    """AMBS decision for one period of the S-CLSP (port of `determine_production_plan` +
    `realize_production_plan`).
    """
    K = env.K
    capacity = int(env.CAP)
    theta = env.st
    a_unif, b_unif = env._unif_a, env._unif_b
    iSU = int(iSU)

    planned_capacity = 0
    planned_production = np.zeros(K, dtype=np.int64)
    new_setup_skus = []
    last_product_determined = False
    last_product_scheduled = None

    while planned_capacity < capacity:
        ebo = np.zeros(K, dtype=np.float64)
        ebo_exceeded = np.zeros(K, dtype=np.float64)

        for i in range(K):
            eligible = (
                i in new_setup_skus
                or i == iSU
                or len(new_setup_skus) < params.Zmax   # STRICT '<'
            )
            if eligible:
                s = float(I[i] + planned_production[i])
                ebo[i] = _expected_backlog_units(a_unif, b_unif, i, s)
            # params.Bmin is already the scaled threshold (xb * mean EOQ cost): do not rescale it by C[i].
            ebo_exceeded[i] = max(ebo[i] - params.Bmin, 0.0)

        if ebo_exceeded.max() > 0.0:
            i_best = int(np.argmax(ebo_exceeded))

            if i_best not in new_setup_skus and i_best != iSU:
                new_setup_skus.append(i_best)
                planned_capacity += int(theta[i_best])
                if planned_capacity >= capacity:
                    last_product_determined = True
                    last_product_scheduled = i_best

            if planned_capacity < capacity:
                planned_production[i_best] += 1
                planned_capacity += 1

        else:
            produced_skus = [iSU] + new_setup_skus

            if len(produced_skus) <= 2:
                last_product_determined = True
                last_product_scheduled = produced_skus[0] if len(produced_skus) == 1 else produced_skus[1]

                i0 = produced_skus[0]
                while planned_capacity < capacity:
                    if I[i0] + planned_production[i0] + 1 < params.Hmax * Q[i0]:
                        planned_production[i0] += 1
                        planned_capacity += 1
                    else:
                        break
            else:
                inv_ratio_new = [
                    (planned_production[s] + I[s]) / Q[s] for s in new_setup_skus
                ]
                last_product_scheduled = new_setup_skus[int(np.argmin(inv_ratio_new))]
                last_product_determined = True
                produced_skus.remove(last_product_scheduled)

                inv_ratio = [
                    (planned_production[s] + I[s]) / Q[s] for s in produced_skus
                ]
                while planned_capacity < capacity and len(produced_skus) > 0:
                    j = int(np.argmin(inv_ratio))
                    s = produced_skus[j]
                    if I[s] + planned_production[s] + 1 < params.Hmax * Q[s]:
                        planned_production[s] += 1
                        planned_capacity += 1
                    else:
                        produced_skus.pop(j)
                        inv_ratio.pop(j)

            while planned_capacity < capacity and last_product_determined:
                s = last_product_scheduled
                if I[s] + planned_production[s] + 1 < params.Hmax * Q[s]:
                    planned_production[s] += 1
                    planned_capacity += 1
                else:
                    planned_capacity = capacity  # force stop

    if not last_product_determined:
        if len(new_setup_skus) == 0:
            last_product_scheduled = iSU
        else:
            inv_ratio_new = [
                (planned_production[s] + I[s]) / Q[s] for s in new_setup_skus
            ]
            last_product_scheduled = new_setup_skus[int(np.argmin(inv_ratio_new))]

    last_product_scheduled = int(last_product_scheduled)

    # Realize the plan at unit precision (no restricted action grid), as in AMBS_Heuristic_SCLSP.ipynb.
    order = []
    if planned_production[iSU] > 0 and iSU != last_product_scheduled:
        order.append(iSU)
    mid_skus = [
        int(i) for i in range(K)
        if i not in (iSU, last_product_scheduled) and planned_production[i] > 0
    ]
    mid_skus.sort(key=lambda i: planned_production[i], reverse=True)
    order.extend(mid_skus)
    if planned_production[last_product_scheduled] > 0 or last_product_scheduled == iSU:
        order.append(last_product_scheduled)

    q = np.zeros(K, dtype=np.int64)
    capacity_used = 0
    current_setup = iSU

    for i in order:
        remaining = capacity - capacity_used
        if remaining <= 0:
            break
        needs_setup = (i != current_setup)
        if needs_setup:
            remaining -= int(theta[i])
            if remaining <= 0:
                continue
            capacity_used += int(theta[i])
            current_setup = i

        produced_qty = min(int(planned_production[i]), capacity - capacity_used)
        if produced_qty <= 0:
            continue
        q[i] = produced_qty
        capacity_used += produced_qty

    return q, order


class _AMBSSDEngine:
    """AMBS-SD decisions (port of `AMBSSDHeuristic` in AMBS_Heuristic_SCLSP_SD.ipynb), built from a
    CLSPHierEnv2.
    """

    EPS = 1e-9

    def __init__(self, env):
        self.K = int(env.K)
        self.capacity = float(env.CAP)
        self.k_sd = np.asarray(env.k_sd, dtype=np.float64)
        self.st_sd = np.asarray(env.st_sd, dtype=np.float64)
        self.a_unif = np.asarray(env._unif_a)
        self.b_unif = np.asarray(env._unif_b)
        mu = np.asarray(env.mu, dtype=np.float64)
        h = np.asarray(env.h, dtype=np.float64)
        K = self.K
        k_eoq = np.zeros(K, dtype=np.float64)
        tot, cnt = 0.0, 0
        for i in range(K):
            acc = 0.0
            for j in range(K):
                if j != i:
                    acc += float(self.k_sd[j, i])
                    tot += float(self.k_sd[j, i])
                    cnt += 1
            k_eoq[i] = acc / (K - 1) if K > 1 else 0.0
        self.c_bar = tot / cnt if (cnt > 0 and tot > 0.0) else 1.0
        self.Q = np.maximum(np.ceil(np.sqrt(2.0 * mu * k_eoq / h)), 1).astype(np.int64)

    def _ebo(self, i, x):
        return _expected_backlog_units(self.a_unif, self.b_unif, i, x)

    def best_insertion(self, start, path, end, i):
        k, st = self.k_sd, self.st_sd
        n = len(path)
        best = None
        for pos in range(n, -1, -1):
            prev = start if pos == 0 else path[pos - 1]
            nxt = path[pos] if pos < n else end
            dc = k[prev, i]
            dt = st[prev, i]
            if nxt >= 0:
                dc += k[i, nxt] - k[prev, nxt]
                dt += st[i, nxt] - st[prev, nxt]
            if best is None or dc < best[1] - self.EPS or (abs(dc - best[1]) <= self.EPS and dt < best[2] - self.EPS):
                best = (pos, float(dc), float(dt))
        return best

    def plan(self, inventory, iSU, params):
        K, capacity, EPS = self.K, self.capacity, self.EPS
        planned = np.zeros(K, dtype=np.int64)
        new_setup_skus, path = [], []
        units, setup_time = 0, 0.0
        in_new = np.zeros(K, dtype=bool)
        blocked = np.zeros(K, dtype=bool)
        last_determined, last = False, None

        def room_for_unit():
            return units + setup_time + 1.0 <= capacity + EPS

        ebo_raw = np.array([self._ebo(i, float(inventory[i])) for i in range(K)])
        ins = [None] * K

        def refresh_insertions():
            for i in range(K):
                ins[i] = None if (i == iSU or in_new[i]) else self.best_insertion(iSU, path, -1, i)

        refresh_insertions()
        stop = False
        while not stop and room_for_unit():
            can_open = len(new_setup_skus) < params.Zmax
            score = np.zeros(K, dtype=np.float64)
            for i in range(K):
                is_new_setup = not (in_new[i] or i == iSU)
                eligible = (not is_new_setup) or (can_open and not blocked[i])
                v = (ebo_raw[i] - params.Bmin) if eligible else -params.Bmin
                v = v if v > 0.0 else 0.0
                if v > 0.0 and is_new_setup and params.lam > 0.0:
                    v /= (1.0 + params.lam * ins[i][1] / self.c_bar)
                score[i] = v
            i_best = int(np.argmax(score))

            if score[i_best] > 0.0:
                if not in_new[i_best] and i_best != iSU:
                    pos, _dc, dt = ins[i_best]
                    if units + setup_time + dt + 1.0 > capacity + EPS:
                        blocked[i_best] = True
                        continue
                    new_setup_skus.append(i_best)
                    in_new[i_best] = True
                    path.insert(pos, i_best)
                    setup_time += dt
                    refresh_insertions()
                planned[i_best] += 1
                units += 1
                ebo_raw[i_best] = self._ebo(i_best, float(inventory[i_best] + planned[i_best]))
            else:
                produced = [iSU] + new_setup_skus
                if len(produced) <= 2:
                    last_determined = True
                    last = produced[0] if len(produced) == 1 else produced[1]
                    i0 = produced[0]
                    while room_for_unit():
                        if inventory[i0] + planned[i0] + 1 < params.Hmax * self.Q[i0]:
                            planned[i0] += 1
                            units += 1
                        else:
                            break
                else:
                    ratio_new = [(planned[s] + inventory[s]) / self.Q[s] for s in new_setup_skus]
                    last = new_setup_skus[int(np.argmin(ratio_new))]
                    last_determined = True
                    produced.remove(last)
                    ratio = [(planned[s] + inventory[s]) / self.Q[s] for s in produced]
                    while room_for_unit() and len(produced) > 0:
                        j = int(np.argmin(ratio))
                        s_ = produced[j]
                        if inventory[s_] + planned[s_] + 1 < params.Hmax * self.Q[s_]:
                            planned[s_] += 1
                            units += 1
                        else:
                            produced.pop(j)
                            ratio.pop(j)
                while not stop and room_for_unit() and last_determined:
                    s_ = last
                    if inventory[s_] + planned[s_] + 1 < params.Hmax * self.Q[s_]:
                        planned[s_] += 1
                        units += 1
                    else:
                        stop = True
                stop = True

        if not last_determined:
            if len(new_setup_skus) == 0:
                last = iSU
            else:
                ratio_new = [(planned[s] + inventory[s]) / self.Q[s] for s in new_setup_skus]
                last = new_setup_skus[int(np.argmin(ratio_new))]
        return planned, path, int(last)

    def sequence(self, planned, path, iSU, last):
        order = []
        if planned[iSU] > 0 and iSU != last:
            order.append(iSU)
        last_in = planned[last] > 0 or last == iSU
        end = last if (last_in and last != iSU) else -1
        mid = []
        for m in path:
            if m == last or m == iSU or planned[m] <= 0:
                continue
            pos, _dc, _dt = self.best_insertion(iSU, mid, end, m)
            mid.insert(pos, m)
        order.extend(mid)
        if last_in:
            order.append(last)
        return order

    def realize(self, planned, order, iSU):
        EPS = self.EPS
        q = np.zeros(self.K, dtype=np.int64)
        used = 0.0
        current = iSU
        for i in order:
            remaining = self.capacity - used
            if remaining < 1.0 - EPS:
                break
            if i != current:
                st = float(self.st_sd[current, i])
                if remaining - st < 1.0 - EPS:
                    continue
                used += st
                current = i
            room = int(np.floor(self.capacity - used + EPS))
            qi = min(int(planned[i]), room)
            if qi <= 0:
                continue
            q[i] = qi
            used += qi
        return q

    def decide(self, inventory, iSU, params):
        """Returns (q, order): realized AMBS-SD quantities and production sequence (products actually
        produced, in sequence order).
        """
        planned, path, last = self.plan(inventory, int(iSU), params)
        order = self.sequence(planned, path, int(iSU), last)
        q = self.realize(planned, order, int(iSU))
        return q, [int(i) for i in order if q[int(i)] > 0]


def _current_setup_idx(env, is_sd):
    return int(env.current_setup_idx()) if is_sd else int(np.argmax(env.omega))


def _rank_scores_from_order(K, order):
    """Strictly descending pseudo scores that reproduce `order` in `plan_quantity_assignment_order`."""
    scores = np.zeros(K, dtype=np.float32)
    n = len(order)
    for pos, i in enumerate(order):
        scores[int(i)] = np.float32(1.0 - pos / (n + 1))
    return scores


# Applying one AMBS decision to a real env (state transition)
def _collect_period_rows(env, q, order, is_sd):
    """Build the HIGH row of one period and the LOW actions that make env.step() execute the AMBS quantities
    `q`.
    """
    K = env.K
    a_high = (np.asarray(q) > 0).astype(np.int8)
    elig_mask = env.eligibility_mask_high().astype(np.float32)
    a_high_label = a_high.astype(np.float32) * elig_mask  # defensive: never label an ineligible dim as 1
    obs_high = env._obs_high().astype(np.float32)
    high_row = (obs_high, elig_mask, a_high_label)

    scores = np.zeros(K, dtype=np.float32)
    low_fracs = []

    if a_high.sum() > 0:
        scores = _rank_scores_from_order(K, order)
        chosen = env.plan_quantity_assignment_order(a_high, scores)

        CAP_rem = env.low_capacity_start(a_high) if is_sd else int(env.CAP)
        I_view = env.I.copy()
        prev_idx = _current_setup_idx(env, is_sd) if is_sd else None

        for pos, i in enumerate(chosen):
            i = int(i)
            if is_sd:
                _low_obs, q_cap, need_setup = env._low_state_mask_for(
                    i, CAP_rem, a_high_scores=scores, pos=pos, chosen=chosen,
                    I_view=I_view, a_high_vec=a_high, prev_idx=prev_idx,
                )
            else:
                _low_obs, q_cap, need_setup = env._low_state_mask_for(
                    i, CAP_rem, a_high_scores=scores, pos=pos, chosen=chosen,
                    I_view=I_view, a_high_vec=a_high,
                )

            q_i = int(min(int(q[i]), q_cap))
            # Fraction of q_cap itself (NOT the fixed env.CAP), matching the `low_action_to_qty` scale
            frac = float(np.clip((q_i + 0.5) / float(max(1, q_cap)), 0.0, 1.0)) if q_i > 0 else 0.0
            low_fracs.append(frac)

            if q_i > 0:
                if need_setup:
                    if is_sd:
                        st_ij = env.low_setup_charge(prev_idx, i)
                    else:
                        st_ij = int(env.st[i])
                    CAP_rem -= st_ij
                CAP_rem = max(0, CAP_rem - q_i)
                I_view[i] = I_view[i] + q_i * env.bs[i]
                if is_sd:
                    prev_idx = i

    return high_row, a_high, scores, low_fracs


# Dataset collection: (state, action) pairs for HIGH
def collect_ambs_dataset(env, params, is_sd, n_periods, n_rollouts, warmup_periods,
                          seed_base, gamma, verbose=True):
    """Collect AMBS (state, action) pairs for HIGH plus critic targets (mean/std-normalized global reward,
    discounted with `gamma`).
    """
    K = env.K

    if is_sd:
        engine = _AMBSSDEngine(env)
    else:
        Q = _eoq_ceil(env.mu, env.k, env.h)
        C = _eoq_cost(env.mu, env.k, env.h, Q)

    n_rollouts = max(1, int(n_rollouts))
    periods_per_rollout = max(1, int(math.ceil(n_periods / n_rollouts)))

    # Guard: otherwise every collected period would be discarded as warm-up.
    if warmup_periods >= periods_per_rollout:
        clamped = max(0, periods_per_rollout // 5)
        if verbose:
            print(f"[warm-start] warmup_periods={warmup_periods} >= periods_per_rollout="
                  f"{periods_per_rollout}; clamping warmup to {clamped} so the dataset "
                  f"isn't empty. Consider raising `dataset_periods`.")
        warmup_periods = clamped

    all_rewards, all_high_rows = [], []

    for r in range(n_rollouts):
        seed_r = int(seed_base + 1000 * r)
        env.reset(seed=seed_r)
        I = env.I.copy()
        iSU = _current_setup_idx(env, is_sd)

        r_rewards, r_high_rows = [], []
        t = 0
        while t < periods_per_rollout:
            if is_sd:
                q, order = engine.decide(I, iSU, params)
            else:
                q, order = _ambs_decide_period_nonsd(env, I, iSU, params, Q, C)

            high_row, a_high, scores, low_fracs = _collect_period_rows(env, q, order, is_sd)

            has_prod = bool(a_high.sum() > 0)
            _obs_next, _reward, term, trunc, info = env.step(
                a_high,
                low_actions=(low_fracs if has_prod else None),
                a_high_scores=(scores if has_prod else None),
            )
            reward_t = -float(info["cost"])

            if t >= warmup_periods:
                r_rewards.append(reward_t)
                r_high_rows.append(high_row + ((list(order) if has_prod else []),))

            I = env.I.copy()
            iSU = _current_setup_idx(env, is_sd)
            t += 1

            if term or trunc:
                seed_r += 500_000
                env.reset(seed=seed_r)
                I = env.I.copy()
                iSU = _current_setup_idx(env, is_sd)

        all_rewards.append(r_rewards)
        all_high_rows.append(r_high_rows)

    # Reward normalization mirrors buffers.py's normalize_rewards=True default
    flat = np.concatenate([np.asarray(rr, dtype=np.float32) for rr in all_rewards if len(rr) > 0]) \
        if any(len(rr) > 0 for rr in all_rewards) else np.zeros(0, dtype=np.float32)
    r_mean = float(flat.mean()) if flat.size > 0 else 0.0
    r_std = max(float(flat.std()) if flat.size > 0 else 1.0, 1e-8)

    high_obs, high_mask, high_act, high_ret, high_order = [], [], [], [], []

    for r_rewards, r_high_rows in zip(all_rewards, all_high_rows):
        if len(r_rewards) == 0:
            continue
        norm_r = (np.asarray(r_rewards, dtype=np.float32) - r_mean) / (r_std + 1e-8)
        rets = discount_cumsum(norm_r, gamma)
        for (obs_h, mask_h, act_h, ord_h), G in zip(r_high_rows, rets):
            high_obs.append(obs_h)
            high_mask.append(mask_h)
            high_act.append(act_h)
            high_ret.append(G)
            padded = np.full(K, -1, dtype=np.int64)
            padded[:len(ord_h)] = ord_h
            high_order.append(padded)

    return dict(
        obs=np.asarray(high_obs, dtype=np.float32) if high_obs else np.zeros((0, env.observation_space.shape[0]), np.float32),
        mask=np.asarray(high_mask, dtype=np.float32) if high_mask else np.zeros((0, K), np.float32),
        act=np.asarray(high_act, dtype=np.float32) if high_act else np.zeros((0, K), np.float32),
        ret=np.asarray(high_ret, dtype=np.float32) if high_ret else np.zeros((0,), np.float32),
        order=np.asarray(high_order, dtype=np.int64) if high_order else np.zeros((0, K), np.int64),
    )


# Behavior cloning (MLE under the same distributions PPO uses)
def _train_val_split(N, val_frac, generator):
    perm = torch.randperm(N, generator=generator)
    if N <= 1:
        return perm, perm[:0]
    n_val = min(max(1, int(N * val_frac)), N - 1)
    return perm[n_val:], perm[:n_val]


def _plot_pretrain_curves(train_curve, val_curve, agent_label, save_path, verbose=True):
    """Save a PNG of train/val NLL per epoch."""
    try:
        epochs = np.arange(1, len(train_curve) + 1)
        plt.figure()
        plt.plot(epochs, train_curve, label="Train NLL")
        plt.plot(epochs, val_curve, label="Val NLL")
        plt.xlabel("Epoch"); plt.ylabel("Negative log-likelihood")
        plt.title(f"Warm start – {agent_label} pretrain loss")
        plt.grid(True); plt.legend(); plt.tight_layout()
        plt.savefig(save_path, dpi=150)
        plt.close()
        if verbose:
            print(f"[warm-start][{agent_label}] loss curve saved to {save_path}")
    except Exception as e:
        if verbose:
            print(f"[warm-start][{agent_label}] failed to save loss curve: {e}")


def _ranking_loss(logits, order):
    """Pairwise ranking loss on consecutive products of the AMBS sequence; returns (loss, pair accuracy)."""
    a, b = order[:, :-1], order[:, 1:]
    valid = (a >= 0) & (b >= 0)
    if not bool(valid.any()):
        zero = logits.sum() * 0.0
        return zero, float("nan")
    la = torch.gather(logits, 1, a.clamp(min=0))
    lb = torch.gather(logits, 1, b.clamp(min=0))
    diff = (la - lb)[valid]
    return F.softplus(-diff).mean(), float((diff > 0).float().mean().item())


def _pretrain_high(net, dataset, device, epochs=8, lr=3e-4, batch_size=256,
                    entropy_coef=1e-2, value_coef=0.5, rank_coef=0.0,
                    val_frac=0.1, seed=0, verbose=True, plot_path=None):
    N = dataset["obs"].shape[0]
    if N == 0:
        if verbose:
            print("[warm-start][HIGH] empty dataset, skipping.")
        return {"n_samples": 0}

    obs = torch.as_tensor(dataset["obs"], dtype=torch.float32, device=device)
    mask = torch.as_tensor(dataset["mask"], dtype=torch.float32, device=device)
    act = torch.as_tensor(dataset["act"], dtype=torch.float32, device=device)
    ret = torch.as_tensor(dataset["ret"], dtype=torch.float32, device=device)
    use_rank = rank_coef > 0.0 and "order" in dataset
    order = torch.as_tensor(dataset["order"], dtype=torch.long, device=device) if use_rank else None

    g = torch.Generator().manual_seed(int(seed))
    train_idx, val_idx = _train_val_split(N, val_frac, g)

    opt = torch.optim.Adam(net.parameters(), lr=lr, eps=1e-5)
    best_val, best_state = None, copy.deepcopy(net.state_dict())
    train_nll_curve, val_nll_curve = [], []

    for ep in range(epochs):
        net.train()
        ep_perm = train_idx[torch.randperm(train_idx.numel())]
        ep_train_nll, ep_batches = 0.0, 0
        for j in range(0, ep_perm.numel(), batch_size):
            b = ep_perm[j:j + batch_size]
            logits, v = net(obs[b])
            dist = MaskedBernoulli(logits, mask[b])
            nll = -dist.log_prob(act[b]).mean()
            probs = dist.probs
            ent = -(probs * torch.log(probs + 1e-8)
                    + (1 - probs) * torch.log(1 - probs + 1e-8)).sum(dim=-1).mean()
            v_loss = F.mse_loss(v, ret[b])
            loss = nll + value_coef * v_loss - entropy_coef * ent
            if use_rank:
                r_loss = -plackett_luce_log_prob(logits, order[b]).mean()
                loss = loss + rank_coef * r_loss

            opt.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 10.0)
            opt.step()

            ep_train_nll += float(nll.item())
            ep_batches += 1

        train_nll_curve.append(ep_train_nll / max(ep_batches, 1))

        net.eval()
        val_rank_acc = float("nan")
        with torch.no_grad():
            if val_idx.numel() > 0:
                logits, _v = net(obs[val_idx])
                val_nll = float(-MaskedBernoulli(logits, mask[val_idx]).log_prob(act[val_idx]).mean().item())
                if use_rank:
                    _rl, val_rank_acc = _ranking_loss(logits, order[val_idx])
            else:
                val_nll = float("nan")
        val_nll_curve.append(val_nll)

        if verbose:
            rank_txt = f" val_order_acc={val_rank_acc:.3f}" if use_rank else ""
            print(f"[warm-start][HIGH] epoch {ep + 1}/{epochs} "
                  f"train_NLL={train_nll_curve[-1]:.4f} val_NLL={val_nll:.4f}{rank_txt}")

        if best_val is None or (val_nll == val_nll and val_nll < best_val):
            best_val = val_nll
            best_state = copy.deepcopy(net.state_dict())

    net.load_state_dict(best_state)
    net.eval()

    if plot_path is not None:
        _plot_pretrain_curves(train_nll_curve, val_nll_curve, "HIGH", plot_path, verbose=verbose)

    return {
        "n_samples": int(N), "best_val_nll": best_val,
        "train_nll_curve": train_nll_curve, "val_nll_curve": val_nll_curve,
    }


# Public entry point
def _resolve_warm_start_cfg(HYP, explicit, is_sd=False):
    """Resolve the dataset-collection + pretraining hyperparameters of the HIGH warm start."""
    explicit = dict(explicit or {})

    def resolve(key, default):
        if key in explicit and explicit[key] is not None:
            return explicit[key]
        hyp_key = f"warm_start_{key}"
        if HYP.get(hyp_key) is not None:
            return HYP[hyp_key]
        return default

    cfg = {
        "dataset_periods": int(resolve("dataset_periods", DEFAULT_DATASET_PERIODS)),
        "n_rollouts": int(resolve("rollouts", DEFAULT_N_ROLLOUTS)),
        "warmup_periods": int(resolve("warmup_periods", DEFAULT_WARMUP_PERIODS)),
    }
    pk = {
        "epochs": int(resolve("epochs", 8)),
        "lr": float(resolve("lr", 3e-4)),
        "batch_size": int(resolve("batch_size", HYP.get("batch_size", 256))),
        "entropy_coef": float(resolve("entropy_coef", HYP.get("entropy_coef_high", HYP.get("entropy_coef", 1e-2)))),
        "value_coef": float(resolve("value_coef", 0.5)),
        # Plackett-Luce order term on the HIGH logits (S-CLSP-SD only)
        "rank_coef": float(resolve("rank_coef", 1.0)) if is_sd else 0.0,
    }
    # Any remaining explicit pretrain-only overrides (e.g. val_frac) pass through.
    for k in ("val_frac",):
        if k in explicit and explicit[k] is not None:
            pk[k] = explicit[k]
    cfg["pretrain_kwargs"] = pk
    return cfg


def warm_start_policies(trainer, HYP, instance_id, device=None, seed=None,
                         ambs_params=None, warm_start_kwargs=None,
                         verbose=True, force_retrain=False):
    """Pretrain `trainer.high` via AMBS-based behavior cloning, in place, before calling `trainer.train()`.
    `trainer.low` is left untouched.

    :param trainer: An already-constructed ``PPO_Hier``/``PPO_Hier2`` instance (its ``.env`` is only used as
        a template
    :param HYP: The same hyperparameter dict used to build ``trainer``.
    :param instance_id: Paper instance ID (e.g. ``"1.7"``) used to look up calibrated AMBS thresholds in
        ``AMBS_PARAMS_REGISTRY``. Ignored if ``ambs_params`` is given directly.
    :param ambs_params: Optional explicit ``AMBSParams``/``AMBSParamsSD`` instance, bypassing the
        ``AMBS_PARAMS_REGISTRY`` lookup.
    :param warm_start_kwargs: Optional dict overriding warm-start hyperparameters: ``dataset_periods``,
        ``rollouts``, ``warmup_periods``, ``epochs``, ``lr``, ``batch_size``, ``entropy_coef``,
        ``value_coef``, ``rank_coef`` (S-CLSP-SD only; default 1.0), ``val_frac``. Takes priority over
        ``HYP``.
    :param force_retrain: If True, ignore any cached warm-start checkpoint in ``HYP["out_dir"]`` and redo
        the AMBS pretraining.
    :return: Report dict with the AMBS params used and HIGH stats.
    """
    device = device or trainer.device
    seed = int(seed if seed is not None else (trainer.seed or 0))
    is_sd = isinstance(trainer.env, CLSPHierEnv2)

    force_retrain = bool(force_retrain or HYP.get("warm_start_force_retrain", False))
    out_dir = HYP.get("out_dir", ".")
    os.makedirs(out_dir, exist_ok=True)
    high_ckpt_path = os.path.join(out_dir, "high_warmstart.pt")

    report = {"ambs_params": None}

    if not force_retrain and os.path.isfile(high_ckpt_path):
        trainer.high.load_state_dict(torch.load(high_ckpt_path, map_location=device))
        trainer.high.eval()
        if verbose:
            print(f"[warm-start] HIGH: loaded cached warm-start checkpoint from "
                  f"{high_ckpt_path} (skipping AMBS pretraining; pass "
                  f"force_retrain=True to redo it).")
        report["high"] = {"loaded_from_cache": True, "ckpt": high_ckpt_path}
        return report

    if verbose:
        print("=" * 60)
        print(f"[warm-start] AMBS-based warm start of HIGH ({'S-CLSP-SD' if is_sd else 'S-CLSP'}), "
              f"instance_id={instance_id!r}")

    sim_env, _ = trainer._build_eval_env({}, seed=seed)

    params = ambs_params if ambs_params is not None else get_ambs_params(instance_id, is_sd)
    report["ambs_params"] = params

    if verbose:
        lam_txt = f" lam={params.lam:.3f}" if is_sd else ""
        print(f"[warm-start] Using AMBS params: Bmin={params.Bmin:.3f} "
              f"Hmax={params.Hmax:.3f} Zmax={params.Zmax}{lam_txt}")

    cfg = _resolve_warm_start_cfg(HYP, warm_start_kwargs, is_sd=is_sd)

    if verbose:
        print(f"[warm-start] Collecting AMBS imitation dataset (HIGH): "
              f"~{cfg['dataset_periods']} periods over {cfg['n_rollouts']} "
              f"rollouts (warmup={cfg['warmup_periods']}/rollout)...")
    dataset = collect_ambs_dataset(
        sim_env, params, is_sd,
        n_periods=cfg["dataset_periods"], n_rollouts=cfg["n_rollouts"],
        warmup_periods=cfg["warmup_periods"],
        seed_base=seed + 9973,
        gamma=float(HYP.get("gamma_high", HYP.get("gamma", 0.99))),
        verbose=verbose,
    )

    if verbose:
        print(f"[warm-start] Pretraining HIGH actor-critic on "
              f"{dataset['obs'].shape[0]} (state, action) pairs...")
    result_high = _pretrain_high(
        trainer.high, dataset, device=device, seed=seed, verbose=verbose,
        plot_path=os.path.join(out_dir, "warmstart_high_loss.png"), **cfg["pretrain_kwargs"],
    )
    result_high["loaded_from_cache"] = False
    if result_high.get("n_samples", 0) > 0:
        torch.save(trainer.high.state_dict(), high_ckpt_path)
        result_high["ckpt"] = high_ckpt_path
        if verbose:
            print(f"[warm-start] HIGH: pretrained weights saved to {high_ckpt_path}")
    report["high"] = result_high

    if verbose:
        print("[warm-start] Done. HIGH network in `trainer` updated in place.")
        print("=" * 60)

    return report
